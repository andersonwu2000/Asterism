class Translator:
    def __init__(self, locale: str = DEFAULT_LOCALE):
        self.locale = locale if locale in CATALOGUE else DEFAULT_LOCALE
        self.table = CATALOGUE[self.locale]

    def __call__(self, key: str, **kw: Any) -> str:
        """A missing key fails loudly rather than leaking a key or an untranslated string onto a page."""
        text = self.table.get(key)
        if text is None:
            text = CATALOGUE[DEFAULT_LOCALE][key]
        return text.format(**kw) if kw else text

    def has(self, key: str) -> bool:
        return key in self.table or key in CATALOGUE[DEFAULT_LOCALE]

    def group(self, name: str, kind: str, owner: str = "") -> str:
        """Default groups have a display name; the others show as they are named."""
        if kind == "default" and self.has(f"group.{name}"):
            return self(f"group.{name}")
        if kind == "ownership" and owner:
            return self("group.ownership", owner=owner)
        return name

    def js_messages(self) -> dict[str, str]:
        """The texts the page script needs, sent along with each page."""
        keys = [k for k in CATALOGUE[DEFAULT_LOCALE] if k.startswith(("error.", "confirm.", "msg.", "invite.", "group.", "sch.",
                                                                  "nav.", "theme.", "presence.", "mem.", "gone.", "perm.", "me.",
                                                                  "perm_hint.", "rail.", "files.", "local.",
                                                                  "editor.", "pm.", "set.", "bar.", "people.",
                                                                  "chan.", "srch.", "admin.", "col.", "dm.", "ag.", "agp.", "form.", "grp.", "home.",
                                                                  "my.", "kind.", "offline.", "cred.", "quota.", "wr.", "db.", "st.", "act."))]
        return {k: self(k) for k in keys}


LOCALES = list(CATALOGUE)


def pick_locale(chosen: str | None, accept_language: str | None) -> str:
    """The language the person chose (kept with their account); until they choose, the first locale in
    Accept-Language that the catalogue has; otherwise the default."""
    if chosen in CATALOGUE:
        return chosen
    for part in (accept_language or "").split(","):
        tag = part.split(";")[0].strip()
        for loc in CATALOGUE:
            t, l = tag.lower(), loc.lower()
            # exact; a bare language for a regional locale (zh -> zh-TW); a regional tag for a bare one (en-US -> en)
            if t == l or (t and (l.startswith(t + "-") or t.startswith(l + "-"))):
                return loc
    return DEFAULT_LOCALE
